const KEY = 'cmms-pwa-language'
function initialLanguage(): Language {
  try { return localStorage.getItem(KEY) === 'id' ? 'id' : 'en' }
  catch { return 'en' }
}
interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (english: string) => string
}
const Context = createContext<LanguageContextValue | null>(null)
export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, updateLanguage] = useState<Language>(initialLanguage)
  const setLanguage = (next: Language) => {
    updateLanguage(next)
    try { localStorage.setItem(KEY, next) } catch { /* storage unavailable */ }
  }
  useEffect(() => { document.documentElement.lang = language }, [language])
  const value = useMemo(() => ({ language, setLanguage, t: (english: string) => language === 'id' ? (dictionary[english] ?? english) : english }), [language])
  return <Context.Provider value={value}>{children}</Context.Provider>
}
export function useI18n() {
  const value = useContext(Context)
  if (!value) throw new Error('LanguageProvider missing')
  return value
}
